'use server'

import prisma from '@/lib/prisma';
import { getAuthenticatedUser } from '@/lib/supabase/sync-user';
import { 
  generateInterviewQuestions as generateAIQuestions, 
  evaluateInterviewAnswer,
  AnswerEvaluation 
} from '@/lib/ai/gemini';

export async function generateInterviewQuestions(customRole?: string) {
  const auth = await getAuthenticatedUser();
  if (!auth) throw new Error("Unauthorized");
  const { dbUser } = auth;

  // Fetch candidate's latest resume analysis to tailor questions
  const latestResume = await prisma.resume.findFirst({
    where: { userId: dbUser.id },
    orderBy: { createdAt: 'desc' },
    include: { analyses: true }
  });

  const targetRole = customRole?.trim() || latestResume?.analyses[0]?.jobTitle || "Full Stack Engineer";
  const resumeSummary = latestResume?.analyses[0]?.summary || 
    `Candidate possesses skills: ${(latestResume?.analyses[0]?.strengths || []).join(', ') || 'General software engineering'}.`;

  // Generate questions via Gemini AI
  const questionsData = await generateAIQuestions(resumeSummary, targetRole);

  if (questionsData.length === 0) {
    throw new Error("No questions were generated by the AI service. Please try again.");
  }

  // Save to database
  const createdQuestions = [];
  for (const q of questionsData) {
    const newQ = await prisma.interviewQuestion.create({
      data: {
        userId: dbUser.id,
        jobRole: targetRole,
        type: q.type,
        question: q.question,
      }
    });
    createdQuestions.push(newQ);
  }

  return createdQuestions;
}

export async function getInterviewQuestions(category?: string) {
  const auth = await getAuthenticatedUser();
  if (!auth) return [];

  const whereClause: { userId: string; type?: string } = {
    userId: auth.dbUser.id,
  };

  if (category && category !== 'All') {
    whereClause.type = category;
  }

  return await prisma.interviewQuestion.findMany({
    where: whereClause,
    orderBy: { createdAt: 'desc' }
  });
}

export async function toggleQuestionStatus(id: string, isCompleted: boolean) {
  const auth = await getAuthenticatedUser();
  if (!auth) {
    return { success: false, error: "Unauthorized" };
  }
  const userId = auth.dbUser.id;

  const existing = await prisma.interviewQuestion.findUnique({
    where: { id }
  });

  if (!existing) {
    return { success: false, error: "Question not found" };
  }

  if (existing.userId !== userId) {
    return { success: false, error: "Forbidden: You do not own this question" };
  }

  const updated = await prisma.interviewQuestion.update({
    where: { id },
    data: { isCompleted }
  });

  return { success: true, question: updated };
}

export interface StoredQuestionEvaluation {
  answer: string;
  evaluation: AnswerEvaluation;
  evaluatedAt: string;
}

export async function submitInterviewAnswer(
  questionId: string, 
  answerText: string
): Promise<{ success: boolean; evaluation?: AnswerEvaluation; error?: string }> {
  const auth = await getAuthenticatedUser();
  if (!auth) {
    return { success: false, error: "Unauthorized" };
  }
  const userId = auth.dbUser.id;

  const trimmedAnswer = answerText.trim();
  if (!trimmedAnswer || trimmedAnswer.length < 5) {
    return { success: false, error: "Answer is too short. Please provide a detailed response for evaluation." };
  }

  const question = await prisma.interviewQuestion.findUnique({
    where: { id: questionId }
  });

  if (!question) {
    return { success: false, error: "Question not found" };
  }

  if (question.userId !== userId) {
    return { success: false, error: "Forbidden: You do not own this question" };
  }

  try {
    const evaluation = await evaluateInterviewAnswer(
      question.question,
      trimmedAnswer,
      question.jobRole
    );

    const storedData: StoredQuestionEvaluation = {
      answer: trimmedAnswer,
      evaluation,
      evaluatedAt: new Date().toISOString()
    };

    await prisma.interviewQuestion.update({
      where: { id: questionId },
      data: {
        isCompleted: true,
        notes: JSON.stringify(storedData)
      }
    });

    return { success: true, evaluation };
  } catch (error: unknown) {
    const msg = error instanceof Error ? error.message : "Failed to evaluate answer with AI";
    return { success: false, error: msg };
  }
}
